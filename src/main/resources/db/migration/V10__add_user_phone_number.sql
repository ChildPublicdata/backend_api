-- [이 파일이 왜 필요한가]
-- 회원가입 화면이 이메일/비밀번호 외에 전화번호도 받도록 정해져서, app_user에 phone_number 컬럼을 추가함.
--
-- [규칙] 이미 서버에 적용된 마이그레이션(V1~V9)은 절대 수정하지 말 것. 새 번호(V10)로 파일을 추가함.
--
-- [기존 회원은 어떻게 되나] not null + default ''를 줘서, 이미 가입된 회원이 있는 배포 환경에서도
-- 컬럼 추가 자체는 실패하지 않게 함. 이 기능은 아직 프론트가 없어 실제 가입자가 없을 가능성이 높지만,
-- 혹시 있더라도 빈 문자열로 채워두고 이후 정책이 필요하면 그때 별도로 값을 채우면 됨.
alter table app_user add column phone_number varchar(20) not null default '';
